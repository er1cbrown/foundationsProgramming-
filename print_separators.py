# without end specification by default a new line
print("Hello") # a new line is inserted automatically
print("What a nice morning!")
# without sep specification by deafult we have an empty space
print("Hello", "What a great morning!") # an empty space is inserted between the two strings
# end help define what to insert after the first print
print("Je suis ici pour voir les choses", end=' ')
print('bonjour')
# sep help defin what to do between the two strings
print('hello', 'the world', sep='**', end='') #separator and end 
print('bonjour')
